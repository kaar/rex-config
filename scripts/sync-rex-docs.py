#!/usr/bin/env python3
"""Mirror the official Rex documentation as local Markdown files."""

import posixpath
import re
import sys
from pathlib import Path, PurePosixPath
from tempfile import TemporaryDirectory
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
MARKER = ".rex-docs-mirror"

SOURCE = "https://www.superlogical.com/rex/docs/"
PAGE_PATH = r"[a-z0-9-]+(?:/[a-z0-9-]+)*"
PAGE_HEADER = re.compile(
    rf"^---\ntitle: [^\n]+\ncanonical_url: {re.escape(SOURCE)}({PAGE_PATH})\n---\n",
    re.MULTILINE,
)
DOC_LINK = re.compile(
    rf"\]\({re.escape(SOURCE)}({PAGE_PATH})(?:\.md)?(#[^\s)]*)?\)"
)


def download(name):
    with urlopen(SOURCE + name, timeout=30) as response:
        if response.headers.get_content_type() != "text/markdown":
            raise ValueError(f"{name}: expected Markdown")
        return response.read().decode("utf-8").replace("\r\n", "\n")


def sync():
    if DOCS.is_symlink() or (DOCS.exists() and not (DOCS / MARKER).is_file()):
        raise ValueError(f"will not replace an unmanaged path: {DOCS}")

    index = download("llms.txt")
    bundle = download("llms-full.txt")
    headers = list(PAGE_HEADER.finditer(bundle))
    paths = {header[1]: PurePosixPath(header[1] + ".md") for header in headers}
    indexed = {link[1] for link in DOC_LINK.finditer(index)}
    if not headers or headers[0].start() != 0 or len(paths) != len(headers):
        raise ValueError("unexpected page headers in llms-full.txt")
    if indexed != paths.keys():
        raise ValueError("the Rex documentation index and bundle list different pages")

    def localize(text, page):
        def replace(link):
            target = paths.get(link[1])
            if target is None:
                return link[0]
            relative = posixpath.relpath(target, page.parent)
            return f"]({relative}{link[2] or ''})"

        return DOC_LINK.sub(replace, text).rstrip("\n") + "\n"

    pages = {PurePosixPath("README.md"): index}
    for i, header in enumerate(headers):
        end = headers[i + 1].start() if i + 1 < len(headers) else len(bundle)
        pages[paths[header[1]]] = bundle[header.start():end]

    # Stage all pages before touching the current mirror.
    with TemporaryDirectory(prefix=".rex-docs-", dir=ROOT) as temp:
        staged = Path(temp) / "next"
        for page, text in sorted(pages.items()):
            path = staged / page
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(localize(text, page).encode("utf-8"))
        (staged / MARKER).write_bytes(b"Generated by scripts/sync-rex-docs.py.\n")

        previous = Path(temp) / "previous"
        if DOCS.exists():
            DOCS.rename(previous)
        try:
            staged.rename(DOCS)
        except OSError:
            if previous.exists():
                previous.rename(DOCS)
            raise

    print(f"Synced {len(paths)} Rex documentation pages and the index to {DOCS}")


if __name__ == "__main__":
    try:
        sync()
    except (OSError, ValueError) as error:
        sys.exit(f"Rex docs sync failed: {error}")
